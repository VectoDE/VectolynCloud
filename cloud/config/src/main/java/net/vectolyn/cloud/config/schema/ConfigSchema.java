/**
 * JSON Schemas (draft 2020-12) of the configuration files, generated from the model records, for
 * editors with YAML support (VS Code with the YAML extension, IntelliJ, any editor with the
 * yaml-language-server). They give completion, field descriptions by name and a red line under a
 * typo or a wrong type while typing.
 *
 * <p>The schema checks what the strict reader checks: field names, types, enum values, the text
 * formats of sizes and times, which fields are required and that no other field is allowed. The
 * rules across fields and files ({@link net.vectolyn.cloud.config.validation.ConfigValidator}, for
 * example port conflicts or a task's group) stay with the cloud.
 *
 * <p>Generated by reflection over the records with the naming rules of
 * {@link net.vectolyn.cloud.config.io.ConfigMappers} (kebab-case, {@code @JsonProperty} names,
 * lower-case enum values), so no extra library is needed. A test compares the result with the
 * records and with the copies in {@code cloud/dist/schema/}.
 */
public final class ConfigSchema {

    /** The JSON Schema dialect. */
    public static final String DIALECT = "https://json-schema.org/draft/2020-12/schema";
    /** Folder of the schemas, relative to {@code config/}. */
    public static final String DIR = "schema";
    /** Base of the {@code $id} of every schema. */
    public static final String ID_BASE = "https://github.com/VectoDE/VectolynCloud/raw/main/cloud/dist/schema/";

    /** Schema file names by configuration file kind. */
    private static final Map<String, ConfigFormat<?>> FORMATS = new LinkedHashMap<>();

    static {
        FORMATS.put("cloud.schema.json", ConfigFormat.CLOUD);
        FORMATS.put("nodes.schema.json", ConfigFormat.NODES);
        FORMATS.put("group.schema.json", ConfigFormat.GROUP);
        FORMATS.put("task.schema.json", ConfigFormat.TASK);
    }

    private static final JsonMapper JSON = JsonMapper.builder().build();
    private static final JsonNodeFactory NODES = JsonNodeFactory.instance;

    private ConfigSchema() {
    }

    /**
     * The schema file that describes a configuration file.
     *
     * @param configFile file name relative to {@code config/}, for example {@code cloud.yml} or
     *                   {@code groups/lobby.yml}
     * @return the schema file name, for example {@code group.schema.json}; null if there is none
     */
    public static @Nullable String schemaFile(String configFile) {
        if (configFile.equals(CloudHome.CLOUD_FILE)) {
            return "cloud.schema.json";
        }
        if (configFile.equals(CloudHome.NODES_FILE)) {
            return "nodes.schema.json";
        }
        if (configFile.startsWith(CloudHome.GROUPS_DIR + "/")) {
            return "group.schema.json";
        }
        if (configFile.startsWith(CloudHome.TASKS_DIR + "/")) {
            return "task.schema.json";
        }
        return null;
    }

    /**
     * The {@code $schema} reference for the yaml-language-server comment of a configuration file,
     * relative to that file: {@code schema/cloud.schema.json} for {@code cloud.yml},
     * {@code ../schema/group.schema.json} for {@code groups/lobby.yml}.
     *
     * @param configFile file name relative to {@code config/}
     * @return the reference, or null if the file has no schema
     */
    public static @Nullable String reference(String configFile) {
        String schema = schemaFile(configFile);
        if (schema == null) {
            return null;
        }
        String up = configFile.contains("/") ? "../" : "";
        return up + DIR + "/" + schema;
    }

    /**
     * Every schema, as written to {@code config/schema/} and {@code cloud/dist/schema/}: UTF-8 JSON
     * with two-space indentation and LF line ends.
     *
     * @return schema file name to content, in a stable order
     */
    public static Map<String, byte[]> all() {
        Map<String, byte[]> files = new TreeMap<>();
        FORMATS.forEach((file, format) -> files.put(file, render(generate(format, file))));
        return files;
    }

    /**
     * Writes every schema to {@code <home>/config/schema/}, each file only if its content differs.
     * Called when the configuration is opened, so the files match the running version.
     *
     * @param home the cloud home
     * @throws IOException if a file cannot be written, or the folder is a link or a file
     */
    public static void install(CloudHome home) throws IOException {
        Path dir = home.configDir().resolve(DIR);
        RegularPaths.Kind kind = RegularPaths.kind(dir);
        if (kind == RegularPaths.Kind.MISSING) {
            Files.createDirectories(dir);
        } else if (kind != RegularPaths.Kind.DIRECTORY) {
            throw new IOException("config/" + DIR + " is not a plain folder");
        }
        AtomicFileWriter writer = new AtomicFileWriter();
        for (Map.Entry<String, byte[]> entry : all().entrySet()) {
            Path file = dir.resolve(entry.getKey());
            RegularPaths.Kind fileKind = RegularPaths.kind(file);
            if (fileKind == RegularPaths.Kind.FILE
                    && Arrays.equals(Files.readAllBytes(file), entry.getValue())) {
                continue;
            }
            if (fileKind != RegularPaths.Kind.FILE && fileKind != RegularPaths.Kind.MISSING) {
                throw new IOException("config/" + DIR + "/" + entry.getKey() + " is not a regular file");
            }
            writer.write(file, entry.getValue());
        }
    }

    /**
     * The schema of one file format.
     *
     * @param format the format
     * @param name   schema file name, part of {@code $id}
     * @return the schema
     */
    public static ObjectNode generate(ConfigFormat<?> format, String name) {
        Generator generator = new Generator();
        ObjectNode root = NODES.objectNode();
        root.put("$schema", DIALECT);
        root.put("$id", ID_BASE + name);
        root.put("title", "VectolynCloud " + title(name));
        root.put("description", "Generated from the configuration model of VectolynCloud. Reference: "
                + "https://github.com/VectoDE/VectolynCloud/blob/main/docs/cloud/config.md");
        ObjectNode body = generator.object(format.type());
        ObjectNode properties = (ObjectNode) body.get("properties");
        ObjectNode version = NODES.objectNode();
        version.put("type", "integer");
        version.put("minimum", 1);
        version.put("maximum", format.currentVersion());
        version.put("description", "Version of the file format; " + format.currentVersion() + " is current.");
        properties.set(ConfigFormat.VERSION_FIELD, version);
        root.setAll(body);
        if (!generator.defs.isEmpty()) {
            ObjectNode defs = root.putObject("$defs");
            generator.defs.forEach(defs::set);
        }
        return root;
    }

    private static String title(String name) {
        return switch (name) {
            case "cloud.schema.json" -> "cloud.yml";
            case "nodes.schema.json" -> "nodes.yml";
            case "group.schema.json" -> "groups/<name>.yml";
            case "task.schema.json" -> "tasks/<name>.yml";
            default -> name;
        };
    }

    private static byte[] render(ObjectNode schema) {
        String text = JSON.writerWithDefaultPrettyPrinter().writeValueAsString(schema);
        return (text.replace("\r\n", "\n") + "\n").getBytes(StandardCharsets.UTF_8);
    }

    /** Walks the record types once; every nested record becomes one entry in {@code $defs}. */
    private static final class Generator {

        private final Map<String, ObjectNode> defs = new TreeMap<>();
        private final Map<Class<?>, String> names = new LinkedHashMap<>();

        /** The object schema of a record, inline. */
        ObjectNode object(Class<?> type) {
            if (!type.isRecord()) {
                throw new IllegalStateException("not a record: " + type.getName());
            }
            ObjectNode node = NODES.objectNode();
            node.put("type", "object");
            ObjectNode properties = node.putObject("properties");
            ArrayNode required = NODES.arrayNode();
            for (Property property : properties(type)) {
                properties.set(property.name(), schema(property.type()));
                if (property.required()) {
                    required.add(property.name());
                }
            }
            if (!required.isEmpty()) {
                node.set("required", required);
            }
            node.put("additionalProperties", false);
            return node;
        }

        private ObjectNode schema(Type type) {
            ObjectNode node = NODES.objectNode();
            if (type instanceof ParameterizedType parameterized && parameterized.getRawType() == List.class) {
                node.put("type", "array");
                node.set("items", schema(parameterized.getActualTypeArguments()[0]));
                return node;
            }
            if (!(type instanceof Class<?> raw)) {
                throw new IllegalStateException("unsupported type " + type);
            }
            if (raw == String.class) {
                node.put("type", "string");
            } else if (raw == int.class || raw == Integer.class || raw == long.class || raw == Long.class) {
                node.put("type", "integer");
            } else if (raw == boolean.class || raw == Boolean.class) {
                node.put("type", "boolean");
            } else if (raw.isEnum()) {
                node.put("type", "string");
                ArrayNode values = node.putArray("enum");
                for (Object constant : raw.getEnumConstants()) {
                    values.add(enumName((Enum<?>) constant));
                }
            } else if (raw == MemorySize.class) {
                node.put("type", "string");
                node.put("pattern", "^[1-9][0-9]{0,6}[MmGg]$");
                node.put("description", MemorySize.FORMAT);
            } else if (raw == TimeSpan.class) {
                node.put("type", "string");
                node.put("pattern", "^(0|[1-9][0-9]{0,5})[smh]$");
                node.put("description", TimeSpan.FORMAT);
            } else if (raw == TimeOfDay.class) {
                node.put("type", "string");
                node.put("pattern", "^" + TimeOfDay.PATTERN + "$");
                node.put("description", TimeOfDay.FORMAT);
            } else if (raw == JavaSelection.class) {
                ArrayNode any = node.putArray("anyOf");
                any.addObject().put("const", "auto");
                any.addObject().put("type", "integer").put("minimum", 8).put("maximum", 99);
                node.put("description", JavaSelection.FORMAT);
            } else if (raw.isRecord()) {
                node.put("$ref", "#/$defs/" + define(raw));
            } else {
                throw new IllegalStateException("no schema for " + raw.getName());
            }
            return node;
        }

        private String define(Class<?> type) {
            String known = names.get(type);
            if (known != null) {
                return known;
            }
            String name = type.getSimpleName();
            if (names.containsValue(name)) {
                name = type.getName().replace('.', '-').replace('$', '-');
            }
            names.put(type, name);
            defs.put(name, NODES.objectNode()); // placeholder against cycles
            defs.put(name, object(type));
            return name;
        }
    }

    /** One field as the strict reader sees it. */
    private record Property(String name, Type type, boolean required) {
    }

    /**
     * The fields of a record: the parameters of a {@code @JsonCreator} factory if it has one, else
     * the record components. A field is required if it is marked {@code @JsonProperty(required = true)};
     * a missing primitive is read as 0 or false, as the reader does.
     */
    private static List<Property> properties(Class<?> type) {
        List<Property> result = new ArrayList<>();
        for (Method method : type.getDeclaredMethods()) {
            JsonCreator creator = method.getAnnotation(JsonCreator.class);
            if (creator != null && Modifier.isStatic(method.getModifiers())
                    && creator.mode() == JsonCreator.Mode.PROPERTIES) {
                for (Parameter parameter : method.getParameters()) {
                    JsonProperty json = Objects.requireNonNull(parameter.getAnnotation(JsonProperty.class),
                            "creator parameter without @JsonProperty in " + type.getName());
                    result.add(new Property(json.value(), parameter.getParameterizedType(), json.required()));
                }
                return result;
            }
        }
        for (RecordComponent component : type.getRecordComponents()) {
            JsonProperty json = annotation(type, component);
            String name = json != null && !json.value().isEmpty() ? json.value() : kebab(component.getName());
            if (name.equals(ConfigFormat.VERSION_FIELD)) {
                result.add(new Property(name, int.class, true));
                continue;
            }
            boolean required = json != null && json.required();
            result.add(new Property(name, component.getGenericType(), required));
        }
        return result;
    }

    private static @Nullable JsonProperty annotation(Class<?> type, RecordComponent component) {
        try {
            Field field = type.getDeclaredField(component.getName());
            return field.getAnnotation(JsonProperty.class);
        } catch (NoSuchFieldException e) {
            return null;
        }
    }

    /** {@code schemaVersion} to {@code schema-version}, as {@code PropertyNamingStrategies.KEBAB_CASE} does. */
    static String kebab(String name) {
        StringBuilder out = new StringBuilder(name.length() + 4);
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            if (Character.isUpperCase(c)) {
                if (i > 0 && !Character.isUpperCase(name.charAt(i - 1))) {
                    out.append('-');
                }
                out.append(Character.toLowerCase(c));
            } else {
                out.append(c);
            }
        }
        return out.toString();
    }

    private static String enumName(Enum<?> constant) {
        try {
            JsonProperty json = constant.getDeclaringClass().getField(constant.name()).getAnnotation(JsonProperty.class);
            if (json != null && !json.value().isEmpty()) {
                return json.value();
            }
        } catch (NoSuchFieldException e) {
            // fall through to the lower-case name
        }
        return constant.name().toLowerCase(Locale.ROOT);
    }
}
